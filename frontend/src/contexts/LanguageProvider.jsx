export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'bn'
    } catch {
      return 'bn'
    }
  })
  const languageRef = useRef(language)

  useEffect(() => {
    document.documentElement.lang = language
    document.title = language === 'bn'
      ? 'আহ্বান রক্তদান সংস্থা | রক্ত দিন, জীবন বাঁচান'
      : 'Ahoban Blood Donation Organization | Donate Blood, Save Lives'
    const description = document.querySelector('meta[name="description"]')
    if (description) {
      description.content = language === 'bn'
        ? 'আহ্বান রক্তদান সংস্থা — স্বেচ্ছায় রক্তদান, মানবতার বন্ধন।'
        : 'Ahoban Blood Donation Organization — voluntary blood donation, a bond of humanity.'
    }
    try {
      localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // Language remains available in memory when browser storage is disabled.
    }
  }, [language])

  const setLanguage = useCallback((nextLanguage) => {
    const selectedLanguage = nextLanguage === 'en' ? 'en' : 'bn'
    languageRef.current = selectedLanguage
    setLanguageState(selectedLanguage)
  }, [])
  const toggleLanguage = useCallback(() => {
    const nextLanguage = languageRef.current === 'bn' ? 'en' : 'bn'
    languageRef.current = nextLanguage
    setLanguageState(nextLanguage)
  }, [])
  const t = useCallback((text, values = {}) => {
    if (typeof text !== 'string') return ''
    const isEnglish = languageRef.current === 'en'
    let translated = isEnglish
      ? englishTranslations[text] || text
      : banglaTranslations[text] || text
    if (translated === text) {
      for (const [bangla, english] of Object.entries(englishTranslations)) {
        const source = isEnglish ? bangla : english
        const target = isEnglish ? english : bangla
        const parts = source.split(/(\{\w+\})/)
        if (parts.length === 1) continue
        const pattern = new RegExp(`^${parts.map((part) => (
          /^\{\w+\}$/.test(part) ? '(.+?)' : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        )).join('')}$`)
        const match = text.match(pattern)
        if (!match) continue
        let capturedIndex = 1
        translated = target.replace(/\{(\w+)\}/g, () => {
          const value = match[capturedIndex]
          capturedIndex += 1
          return value
        })
        break
      }
    }
    return translated.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '')
  }, [])

  const value = useMemo(
    () => ({ language, setLanguage, toggleLanguage, t }),
    [language, setLanguage, toggleLanguage, t],
  )
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export default LanguageContext
